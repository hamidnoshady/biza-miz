import { describe, expect, it } from "vitest";
import { assertNoEmbeddedMedia, EmbeddedMediaError, findEmbeddedMedia, findEmbeddedMediaDeep, parseMediaUrl } from "./embedded-media-guard";

// A real 1×1 PNG, and a longer payload made of its base64 repeated.
const PNG = "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==";
const LONG = (PNG.replace(/=+$/, "") + "Qx7Zk3").repeat(6);

describe("findEmbeddedMedia — GH #1567 F5 bypass attempts", () => {
  const blocked: Array<[string, string]> = [
    ["plain data:image", `<img src="data:image/png;base64,${PNG}">`],
    ["tiny data URI (the < 20,000-char repro)", "data:image/gif;base64,R0lGODlhAQABAAAAACw="],
    ["upper case", `<IMG SRC="DATA:IMAGE/PNG;BASE64,${PNG}">`],
    ["svg (script carrier)", "data:image/svg+xml;utf8,<svg onload=alert(1)>"],
    ["non-image MIME", "data:application/pdf;base64,JVBERi0xLjQK"],
    ["no MIME, base64 only", "data:;base64,AAAA"],
    ["bare comma payload", "data:,hello"],
    ["decimal entity", "&#100;&#97;&#116;&#97;&#58;image/png;base64,AAAA"],
    ["hex entity without semicolons", "&#x64&#x61&#x74&#x61&#x3a image/png;base64,AAAA"],
    ["named &colon;", "data&colon;image/png;base64,AAAA"],
    ["percent-encoded", "data%3Aimage%2Fpng%3Bbase64%2CAAAA"],
    ["double percent-encoded", "data%253Aimage%252Fpng%253Bbase64%252CAAAA"],
    ["JS escape", "\\u0064ata:image/png;base64,AAAA"],
    ["CSS escape", "background:url(\\64 ata:image/png;base64,AAAA)"],
    ["tab/newline inside scheme", "da\tt\na:image/png;base64,AAAA"],
    ["zero-width inside scheme", "d\u200Bata:image/png;base64,AAAA"],
    ["&Tab; inside scheme", "da&Tab;ta:image/png;base64,AAAA"],
    ["srcset", `<img srcset="data:image/webp;base64,UklGRhYAAABXRUJQ 1x">`],
    ["CSS url()", "<div style=\"background-image:url('data:image/jpeg;base64,/9j/4AAQ')\">"],
    ["raw PNG base64 in JSON", JSON.stringify({ image: PNG })],
    ["raw JPEG base64 unquoted attribute", `<img src=/9j/4AAQSkZJRgABAQEASABIAAD/2wBDAAMCAgMCAgMDAwMEAwMEBQgFBQQEBQoHBwYIDAoMDAsKCwsNDhIQDQ4RDgsLEBYQERMUFRUVDA8XGBYUGBIUFRQ>`],
    ["long unsigned base64 run", `توضیح ${LONG} پایان`],
    ["line-wrapped base64 (76 columns)", (LONG.match(/.{1,76}/g) ?? []).join("\n")],
  ];
  for (const [name, text] of blocked) {
    it(`refuses: ${name}`, () => {
      expect(findEmbeddedMedia(text)).not.toBeNull();
    });
  }

  const allowed: Array<[string, string]> = [
    ["Persian description", "پیراهن نخی مردانه، یقه‌دار، مناسب تابستان. شست‌وشو با آب سرد."],
    ["Gutenberg HTML with a media-library image", '<!-- wp:image {"id":42} --><figure><img src="https://shop.example.com/wp-content/uploads/2026/05/shirt.jpg" alt="پیراهن"/></figure><!-- /wp:image -->'],
    ["the word metadata: in prose", "metadata: image/png files are generated by the camera"],
    ["English with long words", "Supercalifragilisticexpialidocious pneumonoultramicroscopicsilicovolcanoconiosis are words."],
    ["a long SKU list", Array.from({ length: 60 }, (_, i) => `SKU-${1000 + i}`).join(", ")],
    ["a UUID", "media 3f1c2a9e-7b4d-4c3a-9f21-0a1b2c3d4e5f"],
    ["a long URL", `https://cdn.example.com/${"a1B2c3".repeat(30)}/image.jpg`],
    ["the word data with a colon in Persian", "داده‌ها: سایز، رنگ"],
  ];
  for (const [name, text] of allowed) {
    it(`allows: ${name}`, () => {
      expect(findEmbeddedMedia(text)).toBeNull();
    });
  }

  it("searches nested payloads and reports the path", () => {
    const hit = findEmbeddedMediaDeep({ name: "x", images: [{ src: "https://a.example/x.png" }, { src: `data:image/png;base64,${PNG}` }] });
    expect(hit?.path).toBe("images.1.src");
  });

  it("refuses with a typed error naming the field, and never edits the text", () => {
    const text = `<p>متن</p><img src="data:image/png;base64,${PNG}">`;
    const copy = text;
    expect(() => assertNoEmbeddedMedia({ longDescription: text })).toThrow(EmbeddedMediaError);
    try {
      assertNoEmbeddedMedia({ longDescription: text });
    } catch (error) {
      expect((error as EmbeddedMediaError).field).toBe("longDescription");
    }
    expect(text).toBe(copy);
  });
});

describe("parseMediaUrl", () => {
  it("accepts https/http URLs and blank, refuses everything else", () => {
    expect(parseMediaUrl("https://cdn.example.com/a.jpg")).toEqual({ ok: true, value: "https://cdn.example.com/a.jpg" });
    expect(parseMediaUrl("  ")).toEqual({ ok: true, value: null });
    expect(parseMediaUrl(null)).toEqual({ ok: true, value: null });
    expect(parseMediaUrl("data:image/png;base64,AAAA")).toEqual({ ok: false, reason: "embedded_media" });
    expect(parseMediaUrl("javascript:alert(1)")).toEqual({ ok: false, reason: "invalid_media_url" });
    expect(parseMediaUrl("blob:https://x.example/1")).toEqual({ ok: false, reason: "invalid_media_url" });
    expect(parseMediaUrl("file:///etc/passwd")).toEqual({ ok: false, reason: "invalid_media_url" });
    expect(parseMediaUrl("https://user:pw@x.example/a.png")).toEqual({ ok: false, reason: "invalid_media_url" });
    expect(parseMediaUrl("https://x.example/a b.png")).toEqual({ ok: false, reason: "invalid_media_url" });
    expect(parseMediaUrl("/relative.png")).toEqual({ ok: false, reason: "invalid_media_url" });
    expect(parseMediaUrl(`https://x.example/${"a".repeat(2100)}`)).toEqual({ ok: false, reason: "media_url_too_long" });
    expect(parseMediaUrl(42)).toEqual({ ok: false, reason: "invalid_media_url" });
  });

  it("enforces an allow-list of hosts when given", () => {
    const allowedHosts = ["shop.example.com", "media.bizamiz.ir"];
    expect(parseMediaUrl("https://shop.example.com/a.jpg", { allowedHosts }).ok).toBe(true);
    expect(parseMediaUrl("https://cdn.media.bizamiz.ir/a.jpg", { allowedHosts }).ok).toBe(true);
    expect(parseMediaUrl("https://evil.example.org/a.jpg", { allowedHosts })).toEqual({ ok: false, reason: "media_url_host_not_allowed" });
    expect(parseMediaUrl("https://shop.example.com.evil.org/a.jpg", { allowedHosts })).toEqual({ ok: false, reason: "media_url_host_not_allowed" });
  });
});
